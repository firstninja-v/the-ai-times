from __future__ import annotations

import argparse
import json
import subprocess
from datetime import datetime
from pathlib import Path

from .config import ROOT, TEMPLATES_META
from .design import apply_design
from .images import attach_images
from .models import EditionPlan
from .render import render_html, write_edition
from .sample_data import sample_articles

PUBLIC_PREVIEWS = ROOT / "public" / "templates"


def build_preview_plan(template: str, paper_title: str = "The AI Times") -> EditionPlan:
    articles = attach_images(sample_articles())
    sections: dict[str, list[str]] = {}
    for idx, article in enumerate(articles):
        section = "Lead" if idx == 0 else article.category.title()
        article._section = section  # type: ignore[attr-defined]
        sections.setdefault(section, []).append(article.id)

    return EditionPlan(
        paper_title=paper_title,
        date_label=datetime.now().strftime("%A, %B %d, %Y").replace(" 0", " "),
        kicker="ALL THE SIGNAL · NONE OF THE SLOP",
        editor_note="Template preview — generated by The AI Times newspaper studio.",
        weather_line="Clear skies for focused reading.",
        sections=[{"name": k, "article_ids": v} for k, v in sections.items()],
        articles=articles,
        template=template,
    )


def write_preview_html(template: str, paper_title: str = "The AI Times") -> Path:
    if template not in TEMPLATES_META:
        raise ValueError(f"Unknown template: {template}")
    plan = build_preview_plan(template, paper_title=paper_title)
    html = render_html(plan, template_id=template, pages=2)
    html = apply_design(html, font="georgia", color_mode="color", pages=3)
    out_dir = PUBLIC_PREVIEWS / template
    out_dir.mkdir(parents=True, exist_ok=True)
    html_path = write_edition(html, out_dir / "preview.html")
    meta = {
        "id": template,
        **TEMPLATES_META[template],
        "previewHtml": f"/templates/{template}/preview.html",
        "previewImage": f"/templates/{template}/preview.png",
        "generatedAt": datetime.now().isoformat(),
        "pages": 3,
        "articles": len(plan.articles),
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return html_path


def screenshot_preview(template: str) -> Path | None:
    html_path = PUBLIC_PREVIEWS / template / "preview.html"
    png_path = PUBLIC_PREVIEWS / template / "preview.png"
    if not html_path.exists():
        write_preview_html(template)
    script = f"""
const {{ chromium }} = require('playwright-core');
(async () => {{
  const browser = await chromium.launch({{ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] }});
  const page = await browser.newPage({{ viewport: {{ width: 1100, height: 1400 }} }});
  await page.goto('file://{html_path.resolve()}', {{ waitUntil: 'networkidle', timeout: 60000 }});
  await page.screenshot({{ path: '{png_path.resolve()}', fullPage: false }});
  await browser.close();
  console.log('ok');
}})().catch((e) => {{ console.error(e); process.exit(1); }});
"""
    try:
        subprocess.run(["node", "-e", script], check=True, cwd=str(ROOT))
        return png_path if png_path.exists() else None
    except Exception as exc:  # noqa: BLE001
        print(f"[previews] screenshot failed for {template}: {exc}")
        return None


def build_all_previews(paper_title: str = "The AI Times") -> list[dict]:
    catalog = []
    PUBLIC_PREVIEWS.mkdir(parents=True, exist_ok=True)
    for template in TEMPLATES_META:
        print(f"[previews] building {template}")
        write_preview_html(template, paper_title=paper_title)
        screenshot_preview(template)
        meta_path = PUBLIC_PREVIEWS / template / "meta.json"
        catalog.append(json.loads(meta_path.read_text("utf-8")))
    index = {
        "generatedAt": datetime.now().isoformat(),
        "count": len(catalog),
        "templates": catalog,
    }
    (PUBLIC_PREVIEWS / "index.json").write_text(json.dumps(index, indent=2), encoding="utf-8")
    print(f"[previews] wrote catalog → {PUBLIC_PREVIEWS / 'index.json'}")
    return catalog


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build visual newspaper template previews")
    parser.add_argument("--template", choices=sorted(TEMPLATES_META.keys()))
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--title", default="The AI Times")
    args = parser.parse_args(argv)

    if args.all or not args.template:
        build_all_previews(paper_title=args.title)
    else:
        write_preview_html(args.template, paper_title=args.title)
        screenshot_preview(args.template)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
