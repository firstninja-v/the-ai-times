"use client";

import { useEffect, useMemo, useState } from "react";
import Link from "next/link";
import { FALLBACK_TEMPLATES, type TemplateCard } from "@/lib/templates";

type Props = {
  selectedId?: string;
  onSelect?: (id: string) => void;
  /** When true, clicking a card only selects — no external link. */
  selectable?: boolean;
  showLivePreview?: boolean;
  title?: string;
  subtitle?: string;
  ctaHref?: string;
  ctaLabel?: string;
  compact?: boolean;
};

export function TemplateGallery({
  selectedId,
  onSelect,
  selectable = true,
  showLivePreview = true,
  title = "Newspaper templates",
  subtitle = "Click a style to see how your paper looks. Generated by the Python studio.",
  ctaHref,
  ctaLabel = "Open design studio",
  compact = false,
}: Props) {
  const [templates, setTemplates] = useState<TemplateCard[]>(FALLBACK_TEMPLATES);
  const [active, setActive] = useState(selectedId || "classic");
  const [broken, setBroken] = useState<Record<string, boolean>>({});
  const [previewKey, setPreviewKey] = useState(0);

  useEffect(() => {
    if (selectedId) setActive(selectedId);
  }, [selectedId]);

  useEffect(() => {
    void fetch("/api/newspaper/templates")
      .then((r) => r.json())
      .then((data) => {
        if (Array.isArray(data.templates) && data.templates.length) {
          setTemplates(data.templates);
          if (!selectedId) {
            setActive(data.templates[0].id);
          }
        }
      })
      .catch(() => undefined);
  }, [selectedId]);

  const selected = useMemo(
    () => templates.find((t) => t.id === active) ?? templates[0],
    [templates, active],
  );

  function pick(id: string) {
    setActive(id);
    setPreviewKey((k) => k + 1);
    onSelect?.(id);
  }

  return (
    <div className="w-full">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div className="max-w-2xl">
          <p className="text-[12px] font-semibold uppercase tracking-[0.2em] text-[hsl(var(--apple-blue))]">
            Templates
          </p>
          <h2 className="font-display mt-2 text-[clamp(1.8rem,4vw,2.8rem)] font-semibold tracking-[-0.03em]">
            {title}
          </h2>
          <p className="mt-2 text-[15px] leading-relaxed text-[hsl(var(--muted-foreground))]">
            {subtitle}
          </p>
        </div>
        {ctaHref ? (
          <Link href={ctaHref} className="btn-secondary !h-10 !px-4 !text-[13px]">
            {ctaLabel}
          </Link>
        ) : null}
      </div>

      <div
        className={`mt-8 grid gap-4 ${
          compact ? "sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-5" : "sm:grid-cols-2 lg:grid-cols-3"
        }`}
      >
        {templates.map((item) => {
          const isActive = active === item.id;
          const imgBroken = broken[item.id];
          return (
            <button
              key={item.id}
              type="button"
              onClick={() => pick(item.id)}
              className={`overflow-hidden rounded-[20px] border bg-white text-left transition ${
                isActive
                  ? "border-[rgba(0,113,227,0.55)] shadow-[0_0_0_3px_rgba(0,113,227,0.12)]"
                  : "border-black/[0.08] hover:border-black/[0.16]"
              }`}
            >
              <div className={`relative bg-[#eceae4] ${compact ? "aspect-[3/4]" : "aspect-[4/5]"}`}>
                {!imgBroken && item.previewImage ? (
                  // eslint-disable-next-line @next/next/no-img-element
                  <img
                    src={`${item.previewImage}?v=3`}
                    alt={item.name}
                    className="h-full w-full object-cover object-top"
                    onError={() => setBroken((p) => ({ ...p, [item.id]: true }))}
                  />
                ) : (
                  <div className="flex h-full items-end p-4 font-display text-xl font-semibold">
                    {item.name}
                  </div>
                )}
                {selectable && isActive ? (
                  <span className="absolute left-3 top-3 rounded-full bg-[hsl(var(--apple-blue))] px-3 py-1 text-[11px] font-semibold text-white">
                    Selected
                  </span>
                ) : null}
              </div>
              <div className="border-t border-black/[0.06] p-3">
                <div className="font-display text-[1.05rem] font-semibold">{item.name}</div>
                <p className="mt-1 text-[12px] leading-snug text-[hsl(var(--muted-foreground))]">
                  {item.description}
                </p>
              </div>
            </button>
          );
        })}
      </div>

      {showLivePreview && selected?.previewHtml ? (
        <div className="mt-8 overflow-hidden rounded-[24px] border border-black/[0.08] bg-white shadow-[0_20px_50px_-30px_rgba(0,0,0,0.35)]">
          <div className="flex items-center justify-between border-b border-black/[0.06] px-4 py-3">
            <div className="text-[12px] font-semibold uppercase tracking-[0.14em] text-[hsl(var(--muted-foreground))]">
              Live look · {selected.name}
            </div>
            <a
              href={selected.previewHtml}
              target="_blank"
              rel="noreferrer"
              className="text-[12px] font-semibold text-[hsl(var(--apple-blue))]"
            >
              Open full size →
            </a>
          </div>
          <iframe
            key={`${selected.id}-${previewKey}`}
            title={`${selected.name} preview`}
            src={`${selected.previewHtml}?t=${previewKey}`}
            className="h-[min(70vh,820px)] w-full bg-[#f4f1ea]"
          />
        </div>
      ) : null}
    </div>
  );
}
